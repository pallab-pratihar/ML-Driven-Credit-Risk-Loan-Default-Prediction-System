"""Run the SQL analytics layer against the processed dataset with DuckDB.

SQL lives in ``sql/analytics.sql`` and is deliberately kept out of the Python
preprocessing code: the analytics layer answers business questions, the Python
layer prepares model inputs.
"""

from __future__ import annotations

import re
from pathlib import Path

import duckdb
import pandas as pd

from src import config

QUERY_HEADER = re.compile(r"^--\s*name:\s*(\S+)\s*$", re.MULTILINE)


def parse_queries(sql_path: Path = config.SQL_DIR / "analytics.sql") -> dict[str, str]:
    """Split the SQL file into ``{query_name: sql_text}`` on ``-- name:`` headers."""
    if not sql_path.exists():
        raise FileNotFoundError(f"SQL file not found: {sql_path}")
    text = sql_path.read_text()
    matches = list(QUERY_HEADER.finditer(text))
    queries: dict[str, str] = {}
    for i, match in enumerate(matches):
        start = match.end()
        end = matches[i + 1].start() if i + 1 < len(matches) else len(text)
        queries[match.group(1)] = text[start:end].strip()
    if not queries:
        raise ValueError(f"No '-- name:' query headers found in {sql_path}")
    return queries


def run_queries(
    df: pd.DataFrame,
    sql_path: Path = config.SQL_DIR / "analytics.sql",
    table_name: str = "loans",
) -> dict[str, pd.DataFrame]:
    """Execute every query in the file against ``df`` and return the results."""
    queries = parse_queries(sql_path)
    results: dict[str, pd.DataFrame] = {}
    with duckdb.connect(database=":memory:") as connection:
        connection.register(table_name, df)
        for name, sql in queries.items():
            results[name] = connection.execute(sql).fetchdf()
    return results


def results_to_markdown(results: dict[str, pd.DataFrame]) -> str:
    """Render all query results as one markdown report."""
    blocks = ["# SQL Portfolio Analytics\n",
              "_Generated by `src/analytics/runner.py` from `sql/analytics.sql`._\n"]
    for name, frame in results.items():
        blocks.append(f"\n## {name}\n")
        blocks.append(frame.to_markdown(index=False))
        blocks.append("")
    return "\n".join(blocks)


def save_report(results: dict[str, pd.DataFrame], path: Path = config.SQL_RESULTS_FILE) -> Path:
    """Write the markdown analytics report to ``reports/``."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(results_to_markdown(results))
    return path
